use winmakase_keymap::{AppWindowRule, WindowRuleState, render_glazewm_config};

const BASE: &str = r#"# machine facts stay in the base
workspaces:
  - name: '1'
  - name: '2'
window_rules:
  - commands: ['ignore']
    match:
      - window_process: { equals: 'zebar' }
"#;

fn app(
    name: &str,
    process: &str,
    class: Option<&str>,
    title: Option<&str>,
    app_id: Option<&str>,
    workspace: Option<&str>,
    state: WindowRuleState,
) -> AppWindowRule {
    AppWindowRule {
        name: name.into(),
        process: process.into(),
        class: class.map(str::to_string),
        title: title.map(str::to_string),
        app_id: app_id.map(str::to_string),
        workspace: workspace.map(str::to_string),
        has_owner: None,
        resizable: None,
        state,
    }
}

#[test]
fn deterministic_rules_match_the_golden() {
    let apps = vec![
        app(
            "browser",
            "chrome",
            None,
            None,
            Some("Chrome"),
            Some("2"),
            WindowRuleState::Tiling,
        ),
        app(
            "preferences",
            "Acme",
            Some("AcmeDialog"),
            Some("Preferences"),
            None,
            None,
            WindowRuleState::Floating,
        ),
        app(
            "browser-pip",
            "chrome",
            Some("Chrome_WidgetWin_1"),
            Some("Picture in picture"),
            None,
            None,
            WindowRuleState::Ignored,
        ),
    ];
    let rendered = render_glazewm_config(BASE, &[], &apps).unwrap();
    assert_eq!(rendered, include_str!("golden/glazewm-app-rules.yaml"));

    let parsed: serde_yaml_ng::Value = serde_yaml_ng::from_str(&rendered).unwrap();
    assert!(parsed.get("window_rules").unwrap().is_sequence());
}

