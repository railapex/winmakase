#[test]
fn preserve_homes_move_only_main_windows() {
    let browser = app(
        "browser",
        "chrome",
        None,
        None,
        Some("Chrome"),
        Some("2"),
        WindowRuleState::Preserve,
    );
    let rendered = render_glazewm_config(BASE, &[], &[browser]).unwrap();
    assert!(rendered.contains("move --workspace 2"));
    assert!(rendered.contains("window_has_owner: false"));
    assert!(rendered.contains("window_is_resizable: true"));
    assert!(!rendered.contains("set-tiling"));
    assert!(!rendered.contains("set-floating"));
}

