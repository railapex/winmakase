#[test]
fn narrow_ignore_is_the_only_contradictory_overlap_with_defined_order() {
    let broad = app(
        "browser",
        "chrome",
        None,
        None,
        None,
        Some("2"),
        WindowRuleState::Tiling,
    );
    let popup = app(
        "browser-popup",
        "chrome",
        Some("Chrome_WidgetWin_1"),
        Some("Popup"),
        None,
        None,
        WindowRuleState::Ignored,
    );
    let rendered = render_glazewm_config(BASE, &[], &[broad, popup]).unwrap();
    let ignored = rendered.find("equals: Popup").unwrap();
    let broad = rendered.rfind("equals: chrome").unwrap();
    assert!(ignored < broad, "{rendered}");
}

